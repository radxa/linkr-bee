import { Capacitor, registerPlugin } from "@capacitor/core";

/**
 * Native half of the Linkr Bee MCP server.
 *
 * This module only exposes the Android transport to the app: the HTTP server,
 * bearer token and lifecycle live in Java, while every MCP protocol request and
 * tool call is answered by web/mcp_server.js through the `httpRequest` event.
 */

export type McpBind = "loopback" | "lan";

export type McpState = {
  running: boolean;
  port: number;
  bind: McpBind;
  /** 64 lowercase hex chars, generated natively and never logged. */
  token: string;
  url: string;
  urls: string[];
  foreground: boolean;
  /**
   * False after the user tapped Stop on the foreground-service notification.
   * The next explicit start() re-arms it; the web layer persists enabled=false
   * from a stateChanged carrying autoStart=false.
   */
  autoStart: boolean;
  activeRequests: number;
  lastError: string | null;
};

export type McpHttpRequest = {
  id: string;
  /** MCP is POST; the public A2A agent card is a GET forwarded to the WebView. */
  method: "POST" | "GET";
  path: string;
  body: string;
  remote: string;
  userAgent: string;
  /** Absolute native deadline; reject events delayed by a paused WebView. */
  deadlineMs?: number;
};

export type McpStartConfig = {
  port: number;
  bind: McpBind;
};

export type McpRespondInput = {
  id: string;
  status: number;
  body: string;
};

/**
 * Input for the Android write-approval notification. The id is generated by the
 * WebView and is echoed back in the `approvalAction` event.
 *
 * `deadlineMs` is the WebView's absolute approval deadline (epoch millis): the
 * native notification is dismissed and reported as expired shortly after it, so
 * a frozen or dead renderer cannot leave a stale prompt behind.
 */
export type McpApprovalInput = {
  id: string;
  title?: string;
  body?: string;
  deadlineMs?: number;
};

/**
 * Payload of the `approvalAction` event: the user's Allow/Deny choice. `expired`
 * is true when the native deadline fired instead of a tap (the decision is a
 * deny).
 */
export type McpApprovalAction = {
  id: string;
  approved: boolean;
  expired?: boolean;
};

export interface McpListenerHandle {
  remove(): Promise<void>;
}

export interface LinkrMcpBridge {
  available: true;
  platform: "android";
  start(config: McpStartConfig): Promise<McpState>;
  stop(): Promise<McpState>;
  getState(): Promise<McpState>;
  regenerateToken(): Promise<McpState>;
  respond(input: McpRespondInput): Promise<void>;
  /** Android 13+: ask for POST_NOTIFICATIONS so background approvals can show. */
  requestApprovalPermission(): Promise<void>;
  /**
   * Posts an Allow/Deny notification. Resolves `true` when the notification was
   * posted, `false` when notifications are disabled or POST_NOTIFICATIONS is not
   * granted (Android 13+); it does not reject for a disabled permission.
   */
  showApproval(input: McpApprovalInput): Promise<boolean>;
  cancelApproval(id: string): Promise<void>;
  addListener(
    event: "httpRequest",
    listener: (payload: McpHttpRequest) => void,
  ): Promise<McpListenerHandle>;
  addListener(
    event: "stateChanged",
    listener: (state: McpState) => void,
  ): Promise<McpListenerHandle>;
  addListener(
    event: "approvalAction",
    listener: (payload: McpApprovalAction) => void,
  ): Promise<McpListenerHandle>;
  addListener(
    event: "requestCancelled",
    listener: (payload: { id: string }) => void,
  ): Promise<McpListenerHandle>;
}

type NativeLinkrMcp = {
  start(options: McpStartConfig): Promise<McpState>;
  stop(): Promise<McpState>;
  getState(): Promise<McpState>;
  regenerateToken(): Promise<McpState>;
  respond(options: McpRespondInput): Promise<void>;
  requestApprovalPermission(): Promise<void>;
  // Capacitor can only resolve a JSON object, so the native side returns
  // {posted}; the wrapper below unwraps it to the boolean the bridge promises.
  showApproval(
    options: McpApprovalInput,
  ): Promise<boolean | { posted?: boolean }>;
  cancelApproval(options: { id: string }): Promise<void>;
  // Capacitor resolves the overloads on the JS side; the wrapper below keeps
  // the public bridge typed per event.
  addListener(
    eventName: string,
    listener: (...args: any[]) => any,
  ): Promise<McpListenerHandle>;
};

const NativeLinkrMcp = registerPlugin<NativeLinkrMcp>("LinkrMcp");

export function createLinkrMcpBridge(): LinkrMcpBridge {
  const bridge = {
    available: true as const,
    platform: "android" as const,
    start: (config: McpStartConfig) => NativeLinkrMcp.start(config),
    stop: () => NativeLinkrMcp.stop(),
    getState: () => NativeLinkrMcp.getState(),
    regenerateToken: () => NativeLinkrMcp.regenerateToken(),
    respond: (input: McpRespondInput) => NativeLinkrMcp.respond(input),
    requestApprovalPermission: () => NativeLinkrMcp.requestApprovalPermission(),
    showApproval: async (input: McpApprovalInput): Promise<boolean> => {
      const result = await NativeLinkrMcp.showApproval(input);
      return typeof result === "boolean" ? result : result?.posted === true;
    },
    cancelApproval: (id: string) => NativeLinkrMcp.cancelApproval({ id }),
    addListener: (event: string, listener: (data: any) => void) =>
      NativeLinkrMcp.addListener(event, listener),
  };
  return bridge as unknown as LinkrMcpBridge;
}

/**
 * Installs window.LinkrMcp on Android only. The bridge is synchronous (like
 * window.LinkrNativeBle) because app modules read it while their body runs.
 */
export function installLinkrMcpBridge(): void {
  if (!Capacitor.isNativePlatform() || Capacitor.getPlatform() !== "android") {
    return;
  }
  if (!window.LinkrMcp) {
    window.LinkrMcp = createLinkrMcpBridge();
  }
}

declare global {
  interface Window {
    LinkrMcp?: LinkrMcpBridge;
  }
}
